const VOWEL = new Set(Array.from("अआइईउऊऋॠऌॡएऐओऔऽःंँ्"));
const MARK = /[\u093e-\u094d\u0902\u0903\u0901]/;
const ENDINGS = ["ेभ्यः", "ेभ्यो", "ानाम्", "ाणाम्", "ित्वा", "त्वा", "स्य", "ेषु", "ेण", "ेन", "ात्", "ाम्", "ानि", "ाणि", "े", "ो", "ा", "ि", "ी", "ु", "ू", "ै", "ौ", "म्", "ः", "ं"];
const KEYS = Object.keys(LEX).sort((a, b) => b.length - a.length || a.localeCompare(b));

export type GlossWord = { w: string; m: string; reading: string };

function textOf(row: Trio, lang: Lang) {
  return lang === "hi" ? row[1] : lang === "te" ? row[2] : row[0];
}

function direct(token: string, lang: Lang) {
  const row = LEX[token];
  return row ? textOf(row, lang) : "";
}

function segment(token: string) {
  const hits: string[] = [];
  let covered = 0;
  let i = 0;
  let misses = 0;
  while (i < token.length && misses < 4) {
    const key = KEYS.find((item) => item.length >= 2 && token.startsWith(item, i));
    if (key) {
      hits.push(key);
      covered += key.length;
      i += key.length;
      misses = 0;
      continue;
    }
    const ch = token[i] ?? "";
    if (VOWEL.has(ch)) {
      i += 1;
      continue;
    }
    i += 1;
    while (i < token.length && MARK.test(token[i] ?? "")) i += 1;
    misses += 1;
  }
  return { hits, covered };
}

function glossToken(token: string, lang: Lang) {
  const whole = direct(token, lang);
  if (whole) return whole;
  const bare = token.replace(/ऽ/g, "");
  const joined = direct(bare, lang);
  if (joined) return joined;
  const expanded = token.replace(/ऽ/g, "अ");
  const parts = segment(expanded);
  if (parts.hits.length && parts.covered / expanded.length >= 0.55) return parts.hits.map((key) => textOf(LEX[key]!, lang)).join(" · ");
  if (token.endsWith("उवाच") && token.length > "उवाच".length) {
    const who = glossToken(token.slice(0, -"उवाच".length), lang);
    if (who) return lang === "hi" ? `${who} ने कहा` : lang === "te" ? `${who} అన్నారు` : `${who} said`;
  }
  for (const end of ENDINGS) {
    if (!token.endsWith(end) || token.length <= end.length + 1) continue;
    const stem = token.slice(0, -end.length);
    const stemHit = direct(stem, lang) || direct(`${stem}ा`, lang) || direct(`${stem}्`, lang);
    if (stemHit) return stemHit;
    const again = segment(stem);
    if (again.hits.length && again.covered / Math.max(stem.length, 1) >= 0.7) return again.hits.map((key) => textOf(LEX[key]!, lang)).join(" · ");
  }
  if (/^[०-९0-9,]+$/.test(token)) return token;
  return "";
}

/** Each Sanskrit word, with its spoken reading and a meaning in the selected language. */
export function glossWords(sa: string, lang: Lang): GlossWord[] {
  return sa.split(/[\s।॥]+/).map((word) => word.trim()).filter(Boolean).filter((word) => !/^[,.;:]+$/.test(word)).map((word) => {
    const reading = toSpokenLatin(word).replace(/\s+/g, "");
    return { w: word, m: glossToken(word, lang), reading };
  });
}

function phrase(words: GlossWord[]) {
  const parts: string[] = [];
  for (const word of words) {
    if (!word.m || parts[parts.length - 1] === word.m) continue;
    parts.push(word.m);
  }
  return parts.join(" ").replaceAll(" · ", " ");
}

/** The repeated “yā devī … saṃsthitā, namas tasyai” line, as one sentence. */
function refrain(sa: string, lang: Lang, words: GlossWord[]) {
  if (!sa.includes("या देवी") || !sa.includes("संस्थित")) return "";
  const start = words.findIndex((word) => word.w.includes("देवी"));
  const end = words.findIndex((word) => word.w.startsWith("संस्थित"));
  if (start < 0 || end <= start) return "";
  const where = phrase(words.slice(start + 1, end));
  if (!where) return "";
  if (lang === "hi") return `जो देवी ${where} स्थित है, उसे नमस्कार।`;
  if (lang === "te") return `ఎవరైతే దేవి ${where} నెలకొని ఉంటుందో, ఆమెకు నమస్కారం।`;
  return `To the Goddess who abides ${where} — salutation.`;
}

/** One meaning for the whole verse, in the selected language. */
export function verseMeaning(sa: string, lang: Lang): string {
  const words = glossWords(sa, lang);
  const sung = refrain(sa, lang, words);
  if (sung) return sung;
  const line = phrase(words);
  if (!line) return "";
  if (lang === "en") {
    const sentence = line.charAt(0).toUpperCase() + line.slice(1);
    return /[.!?]$/.test(sentence) ? sentence : `${sentence}.`;
  }
  return `${line}।`;
}
